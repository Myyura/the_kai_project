#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createProcessor} from '@mdx-js/mdx';
import matter from 'gray-matter';
import remarkMath from 'remark-math';
import katex from 'katex';
import 'katex/contrib/mhchem';
import {visitMathStyles} from '../src/components/KaiMath/sharedStyles.mjs';
import {readUtf8IfExists, writeFileAtomicSync} from './file-utils.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, 'src/components/KaiMath/sharedStyles.generated.js');
const CSS_OUTPUT = path.join(ROOT, 'src/css/katex-shared.generated.css');

function markdownFiles(directory) {
  let entries;
  try {
    entries = fs.readdirSync(directory, {withFileTypes: true});
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    return [];
  }
  return entries.flatMap((entry) => {
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? markdownFiles(file) : /\.mdx?$/.test(file) ? [file] : [];
  }).sort();
}

export function selectStyles(counts) {
  const styles = {};
  const rules = [];
  let savedBytes = 0;
  for (const [style, count] of [...counts].sort(([a, ac], [b, bc]) => (
    bc - ac || (a < b ? -1 : a > b ? 1 : 0)
  ))) {
    // Only compact repeated numeric layout styles emitted by KaTeX. Colors,
    // fonts, URLs and any other custom content remain inline.
    if (!/^(?:(?:height|width|top|left|bottom|right|margin-(?:left|right|top|bottom)|padding-(?:left|right|top|bottom)|vertical-align|border-bottom-width|font-size|position):[-.\da-z%]+;)+$/.test(style)) continue;
    const token = `kms${rules.length.toString(36)}`;
    // A synthetic ID gives these ordinary declarations priority over KaTeX's
    // class rules, as inline styles had, without overriding !important rules.
    const rule = `:is(.katex,#kai-math-style-priority) .${token}{${style}}`;
    const saving = count * (style.length + ' style=""'.length - token.length - 1) - rule.length;
    if (count < 3 || saving <= 0) continue;
    styles[style] = token;
    rules.push(rule);
    savedBytes += saving;
  }
  return {styles, css: `${rules.join('\n')}\n`, savedBytes};
}

export function generateMathStyles() {
  const processor = createProcessor({format: 'md', remarkPlugins: [remarkMath]});
  const mdxProcessor = createProcessor({remarkPlugins: [remarkMath]});
  const formulas = new Map();
  const visit = (node) => {
    if (node.type === 'math' || node.type === 'inlineMath' || (node.type === 'code' && node.lang === 'math')) {
      const display = node.type !== 'inlineMath';
      const key = JSON.stringify([display, node.value]);
      formulas.set(key, (formulas.get(key) || 0) + 1);
    }
    node.children?.forEach(visit);
  };
  for (const file of [...markdownFiles(path.join(ROOT, 'docs')), ...markdownFiles(path.join(ROOT, 'blog'))]) {
    const parser = file.endsWith('.mdx') ? mdxProcessor : processor;
    visit(parser.parse(matter(fs.readFileSync(file, 'utf8')).content));
  }
  const counts = new Map();
  for (const [key, count] of formulas) {
    const [displayMode, source] = JSON.parse(key);
    try {
      const html = katex.renderToString(source, {
        output: 'htmlAndMathml', displayMode, strict: 'ignore', throwOnError: false, trust: false,
      });
      visitMathStyles(html, (style) => counts.set(style, (counts.get(style) || 0) + count));
    } catch {
      // Existing malformed formulas keep the renderer's normal error fallback.
    }
  }
  const {styles, css, savedBytes} = selectStyles(counts);
  const js = `// Generated by scripts/generate-math-styles.mjs. Do not edit.\nexport default ${JSON.stringify(styles, null, 2)};\n`;
  const cssFile = `/* Generated by scripts/generate-math-styles.mjs. */\n${css}`;
  const check = process.argv.includes('--check');
  for (const [file, content] of [[OUTPUT, js], [CSS_OUTPUT, cssFile]]) {
    const current = readUtf8IfExists(file);
    if (check) {
      if (current !== content) {
        throw new Error(`${path.relative(ROOT, file)} is stale; run yarn math:styles.`);
      }
    } else if (current !== content) {
      writeFileAtomicSync(file, content);
    }
  }
  console.log(`Shared math styles: ${Object.keys(styles).length} rules, ${formulas.size} distinct formulas; estimated HTML saving ${(savedBytes / 1024 ** 2).toFixed(2)} MiB.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateMathStyles();
